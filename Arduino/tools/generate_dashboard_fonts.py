#!/usr/bin/env python3
"""Generate native 1-bit glyphs from locally bundled Nanum Gothic (SIL OFL).

Requires Pillow. 14px includes all modern Hangul syllables for incoming task names.
Other sizes subset the UI vocabulary. No network access is performed.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
source = '\n'.join(p.read_text() for p in (ROOT/'SpaceSmart').glob('Dashboard*.h'))
source += (ROOT/'SpaceSmart'/'DashboardRenderer.cpp').read_text()
source += '\n'.join(p.read_text() for p in (ROOT/'SpaceSmart').glob('Lightbar*') if p.suffix in ('.h','.cpp'))
small = set(range(32, 127)) | {ord(c) for c in source if ord(c) > 127} | {176, 215, 183, 8322}
parts = ['// Generated by tools/generate_dashboard_fonts.py; Nanum Gothic, SIL OFL 1.1.', '#include "DashboardCanvas.h"', 'namespace Dashboard {']
for size in (12, 14, 20, 28, 40, 48, 72, 96):
    codes = small | set(range(0xac00, 0xd7a4)) if size == 14 else small if size <= 20 else set(range(32, 127)) | {176}
    font = ImageFont.truetype(str(ROOT/'resources/fonts'/('NanumGothic-Regular.ttf' if size <= 14 else 'NanumGothic-Bold.ttf')), size)
    glyphs, bits = [], bytearray()
    for code in sorted(codes):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char)
        width, height = right-left, bottom-top
        advance = round(font.getlength(char))
        im = Image.new('L', (max(width, 1), max(height, 1)))
        ImageDraw.Draw(im).text((-left, -top), char, font=font, fill=255)
        offset = len(bits)
        packed = bytearray((width*height+7)//8)
        pixels = im.load()
        for y in range(height):
            for x in range(width):
                if pixels[x,y] >= 100:
                    b = y*width+x
                    packed[b//8] |= 0x80 >> (b%8)
        bits += packed
        glyphs.append(f'{{{code},{offset},{width},{height},{advance},{left},{top}}}')
    parts += [f'static const uint8_t bits{size}[]={{']
    parts += [','.join(f'0x{b:02x}' for b in bits[i:i+32])+',' for i in range(0,len(bits),32)]
    parts += ['};',f'static const Glyph glyphs{size}[]={{']
    parts += [','.join(glyphs[i:i+5])+',' for i in range(0,len(glyphs),5)]
    parts += ['};',f'static const Font font{size}={{glyphs{size},bits{size},{len(glyphs)},{size+2}}};']
    print(size, 'px:',len(glyphs),'glyphs,',len(bits),'bitmap bytes')
parts += ['''const Font& fontFor(int size){if(size>=96)return font96;if(size>=72)return font72;if(size>=48)return font48;if(size>=40)return font40;if(size>=28)return font28;if(size>=20)return font20;if(size>=14)return font14;return font12;}
uint32_t decode(const char*& s){
  const uint8_t first=uint8_t(*s++);if(first<128)return first;
  const int count=first>=0xc2&&first<=0xdf?1:first>=0xe0&&first<=0xef?2:first>=0xf0&&first<=0xf4?3:0;
  if(!count)return '?';
  uint32_t code=first&((1u<<(6-count))-1);
  const char* next=s;for(int i=0;i<count;++i){uint8_t v=uint8_t(*next);if((v&0xc0)!=0x80)return '?';code=(code<<6)|(v&63);++next;}
  s=next;if(code>0x10ffff||(code>=0xd800&&code<=0xdfff)||(count==1&&code<128)||(count==2&&code<2048)||(count==3&&code<65536))return '?';return code;
}
} // namespace Dashboard''']
(ROOT/'SpaceSmart'/'DashboardFonts.cpp').write_text('\n'.join(parts)+'\n')
